"""Outline the admissible faces (points outside every forbidden strip) of strips_9_k5_loose.tex -> strips_9_faces.tex"""
import re

import numpy as np
from matplotlib.path import Path
from scipy.spatial import ConvexHull, HalfspaceIntersection

src = open('strips_9_k5_loose.tex').read()
strips = [np.array([[float(a), float(b)] for a, b in re.findall(r'\(([-\d.]+),([-\d.]+)\)', l)])
          for l in src.splitlines() if 'stripfill' in l]
g = (np.arange(600) + 0.5) / 600
X, Y = np.meshgrid(g, g); C = np.c_[X.ravel(), Y.ravel()]
free = ~np.any([Path(S).contains_points(C) for S in strips], axis=0)


def cross(u, v):
    return u[0] * v[1] - u[1] * v[0]


def halfplane(a, b, p):
    """a.x + c <= 0 form of the side of line ab that contains p"""
    nrm = np.array([b[1] - a[1], a[0] - b[0]]); c = -nrm @ a
    return np.r_[nrm, c] if nrm @ p + c <= 0 else -np.r_[nrm, c]


faces, seen = [], set()
for p in C[free]:
    H = [halfplane(S[0], S[1], p) if cross(S[1] - S[0], p - S[0]) * cross(S[1] - S[0], S[2] - S[0]) < 0
         else halfplane(S[2], S[3], p) for S in strips]
    H += [np.array([-1, 0, 0]), np.array([1, 0, -1]), np.array([0, -1, 0]), np.array([0, 1, -1])]
    key = tuple(np.round(np.array(H)[:, 2], 6))
    if key in seen: continue
    seen.add(key)
    try:
        V = HalfspaceIntersection(np.array(H, float), p).intersections
        faces.append(V[ConvexHull(V).vertices])
    except Exception:
        pass
with open('strips_9_faces.tex', 'w') as f:
    f.write('% generated by make_faces.py: the admissible faces of strips_9_k5_loose.tex\n')
    for V in faces:
        f.write('\\filldraw[fill=white,draw=accentdark,line width=0.5pt] ' + ' -- '.join(f'({x:.4f},{y:.4f})' for x, y in V) + ' -- cycle;\n')
print(len(faces), 'faces, areas', sorted(round(ConvexHull(V).volume, 5) for V in faces))
